import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' })
await page.waitForTimeout(2500)
await page.locator('#objections').scrollIntoViewIfNeeded()
await page.waitForTimeout(800)
const btn = page.locator('#objections .flip').first()
console.log('BEFORE pressed:', await btn.getAttribute('aria-pressed'))
console.log('BEFORE class:', await btn.getAttribute('class'))
await btn.click()
await page.waitForTimeout(900)
console.log('AFTER pressed:', await btn.getAttribute('aria-pressed'))
console.log('AFTER class:', await btn.getAttribute('class'))
const transform = await page.locator('#objections .flip-inner').first().evaluate((el) => getComputedStyle(el).transform)
console.log('INNER TRANSFORM:', transform)
await page.screenshot({ path: 'shots/flip-debug.png' })
await browser.close()
